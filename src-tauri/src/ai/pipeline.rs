#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct Structure {
    pub input_format: String,
    pub output_format: String,
    pub examples: Vec<Example>,
    pub compare_mode: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
#[serde(default)]
pub struct Example {
    pub input: String,
    pub output: String,
}

/// Parses the model's JSON (tolerates text around the object).
pub fn parse_json<T: serde::de::DeserializeOwned>(answer: &str) -> Option<T> {
    if let Ok(v) = serde_json::from_str(answer.trim()) {
        return Some(v);
    }
    let start = answer.find('{')?;
    let end = answer.rfind('}')?;
    (end > start)
        .then(|| serde_json::from_str(&answer[start..=end]).ok())
        .flatten()
}

/// Mode suggested by the structure step.
pub fn suggested_mode(s: &Structure) -> Option<CompareMode> {
    match s.compare_mode.as_deref()? {
        "lines" => Some(CompareMode::Lines { trim: true }),
        "tokens" => Some(CompareMode::Tokens {
            case_sensitive: true,
        }),
        "float" => Some(CompareMode::Float {
            abs_tol: 1e-6,
            rel_tol: 1e-6,
        }),
        _ => None,
    }
}

/// Text for the "verbatim" check: LF line ends, every line trimmed, no
/// leading/trailing empty lines.
pub fn normalize_for_match(s: &str) -> String {
    normalize_newlines(s)
        .lines()
        .map(str::trim)
        .collect::<Vec<_>>()
        .join("\n")
        .trim_matches('\n')
        .to_string()
}

/// An example counts only if its output (non-empty) and its input appear
/// verbatim in the task text (after [`normalize_for_match`]).
pub fn example_in_text(normalized_text: &str, ex: &Example) -> bool {
    let input = normalize_for_match(&ex.input);
    let output = normalize_for_match(&ex.output);
    !output.is_empty() && normalized_text.contains(&output) && normalized_text.contains(&input)
}

/// Splits the model's examples into (verbatim, discarded count); at most
/// [`MAX_EXAMPLES`], duplicates removed.
pub fn verify_examples(task_text: &str, examples: &[Example]) -> (Vec<Example>, usize) {
    let text = normalize_for_match(task_text);
    let mut kept: Vec<Example> = Vec::new();
    let mut discarded = 0;
    for ex in examples {
        if !example_in_text(&text, ex) {
            discarded += 1;
            continue;
        }
        let dup = kept.iter().any(|k| {
            normalize_for_match(&k.input) == normalize_for_match(&ex.input)
                && normalize_for_match(&k.output) == normalize_for_match(&ex.output)
        });
        if !dup && kept.len() < MAX_EXAMPLES {
            kept.push(ex.clone());
        }
    }
    (kept, discarded)
}

/// stdin text: LF line ends and a final newline (unless empty).
pub fn as_stdin(s: &str) -> String {
    let s = normalize_newlines(s);
    if s.is_empty() || s.ends_with('\n') {
        s
    } else {
        format!("{s}\n")
    }
}

#[derive(Deserialize, Default)]
#[serde(default)]
struct InputsAnswer {
    inputs: Vec<String>,
}

/// Generated inputs: stdin form, no duplicates (also of `existing`), not
/// too long, at most [`MAX_INPUTS`].
pub fn clean_inputs(raw: &[String], existing: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for r in raw {
        let s = as_stdin(r);
        if s.len() > MAX_GENERATED_INPUT_BYTES {
            continue;
        }
        let key = normalize_for_match(&s);
        let seen = out
            .iter()
            .chain(existing.iter())
            .any(|e| normalize_for_match(e) == key);
        if !seen {
            out.push(s);
        }
        if out.len() >= MAX_INPUTS {
            break;
        }
    }
    out
}

/// A usable run: exited normally, in time, output complete.
fn valid(o: &StepOutput) -> bool {
    o.exit_code == Some(0) && !o.timed_out && !o.stdout_truncated
}

/// Majority for one input over all surviving solutions (`None` = no valid
/// output). Returns (index of a solution in the largest group, its group's
/// members). Crashes count as disagreement.
pub fn majority(
    mode: &CompareMode,
    outputs: &[Option<&StepOutput>],
) -> Option<(usize, Vec<usize>)> {
    let valid_idx: Vec<usize> = outputs
        .iter()
        .enumerate()
        .filter(|(_, o)| o.is_some_and(valid))
        .map(|(i, _)| i)
        .collect();
    let texts: Vec<&str> = valid_idx
        .iter()
        .map(|&i| outputs[i].map_or("", |o| o.stdout.as_str()))
        .collect();
    let groups = group_outputs(mode, &texts);
    let top = groups.first()?;
    let members: Vec<usize> = top.iter().map(|&g| valid_idx[g]).collect();
    Some((members[0], members))
}

/// Inputs to [`decide_confidence`].
#[derive(Debug, Clone, Default)]
pub struct Evidence {
    pub solutions: usize,
    pub compiled: usize,
    pub survivors: usize,
    pub examples: usize,
    pub tests: usize,
    pub dropped: usize,
    /// Lowest agreement over the generated tests.
    pub min_agreement: Option<f64>,
}

fn pct(x: f64) -> String {
    format!("{:.0} %", x * 100.0)
}

/// Green: the sheet's examples were passed, at least two solutions survived
/// and every test has at least 80 % agreement. Red: no solution survived or
/// no test is left. Yellow otherwise (a hint, not a reliable expectation).
pub fn decide_confidence(e: &Evidence) -> Confidence {
    if e.survivors == 0 {
        let reason = if e.compiled == 0 {
            format!(
                "Keine der {} erzeugten Lösungen ließ sich kompilieren bzw. ausführen.",
                e.solutions
            )
        } else {
            format!(
                "Keine der {} erzeugten Lösungen hat die Beispiele des Aufgabenblatts bestanden.",
                e.solutions
            )
        };
        return Confidence {
            level: ConfidenceLevel::Red,
            reasons: vec![
                reason,
                "Es werden deshalb keine Testfälle erzeugt – die Aufgabe ist für das Modell zu \
                 schwer oder der Text ist unklar. Testfälle bitte von Hand anlegen."
                    .into(),
            ],
        };
    }
    if e.tests == 0 {
        return Confidence {
            level: ConfidenceLevel::Red,
            reasons: vec![
                "Die Lösungen waren sich bei keiner Eingabe mehrheitlich einig; es werden keine \
                 Testfälle erzeugt. Testfälle bitte von Hand anlegen."
                    .into(),
            ],
        };
    }
    let mut yellow: Vec<String> = Vec::new();
    if e.examples == 0 {
        yellow.push(
            "Im Aufgabentext wurden keine Beispiele (wörtlich) gefunden – die Lösungen konnten \
             nicht am Blatt geprüft werden."
                .into(),
        );
    }
    if e.survivors == 1 {
        yellow.push(
            "Nur eine Lösung hat die Prüfung bestanden – kein Mehrheitsvergleich möglich.".into(),
        );
    }
    if let Some(a) = e.min_agreement.filter(|a| *a < GREEN_AGREEMENT) {
        yellow.push(format!(
            "Bei mindestens einem Testfall waren sich die Lösungen nur knapp einig ({}).",
            pct(a)
        ));
    }
    if e.dropped > 0 {
        yellow.push(format!(
            "{} Eingabe(n) verworfen, weil sich die Lösungen nicht einig waren oder alle \
             abstürzten.",
            e.dropped
        ));
    }
    if yellow.is_empty() {
        let agree = e.min_agreement.map_or("100 %".to_string(), pct);
        Confidence {
            level: ConfidenceLevel::Green,
            reasons: vec![format!(
                "{} von {} Lösungen haben alle {} Beispiel(e) des Aufgabenblatts bestanden; \
                 Übereinstimmung der Lösungen je Testfall: mindestens {agree}.",
                e.survivors, e.solutions, e.examples
            )],
        }
    } else {
        yellow.push(
            "Die erwarteten Ausgaben sind nur ein Hinweis – bitte prüfen, bevor danach bewertet \
             wird."
                .into(),
        );
        Confidence {
            level: ConfidenceLevel::Yellow,
            reasons: yellow,
        }
    }
}

