//! Test generation from a confirmed task text.
//!
//! Core rule: the model never writes expected outputs. It writes candidate
//! solutions and test inputs; expected outputs are the outputs of verified
//! solutions, executed in the sandbox (`runner::collect_outputs`).
//!
//! 1. Structure (JSON): input/output format, examples, comparison mode.
//!    Examples must appear verbatim in the task text, else they are dropped.
//! 2. N candidate solutions (temperature 0.7), precheck.
//! 3. Compile in the sandbox, at most one repair round with the compiler
//!    message.
//! 4. Run against the sheet's examples; failing solutions are dropped.
//! 5. Test inputs only (JSON array, at most 10).
//! 6. Majority vote: every surviving solution runs every input; outputs are
//!    grouped per comparison mode, the largest group gives the expectation.
//! 7. Confidence green / yellow / red; red yields no tests.
//!
//! The flow is generic over the model ([`Llm`]) and the sandbox
//! ([`Executor`]), so it is unit-tested with mocks.

use std::future::Future;
use std::time::Instant;

use serde::{Deserialize, Serialize};
use tokio_util::sync::CancellationToken;

use super::llama::{ChatRequest, ChatResponse, Llm};
use super::prompts::{self, SolutionContext, MAX_EXAMPLES, MAX_INPUTS};
use super::AiError;
use crate::runner::compare::{group_outputs, normalize_newlines, CompareMode};
use crate::runner::{languages, CollectedOutputs, StepOutput};

/// Longest accepted task text (the model context is 8192 tokens).
pub const MAX_TASK_CHARS: usize = 12_000;
/// Longest generated test input.
pub const MAX_GENERATED_INPUT_BYTES: usize = 16 * 1024;
/// Share of solutions that must agree for "green".
pub const GREEN_AGREEMENT: f64 = 0.8;
pub const SOLUTION_TEMPERATURE: f32 = 0.7;
const STRUCTURE_TEMPERATURE: f32 = 0.0;
const INPUTS_TEMPERATURE: f32 = 0.4;
const RETRY_TEMPERATURE: f32 = 0.3;
const STRUCTURE_MAX_TOKENS: u32 = 1024;
const SOLUTION_MAX_TOKENS: u32 = 1536;
const INPUTS_MAX_TOKENS: u32 = 1024;

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GenerateRequest {
    pub task_text: String,
    pub language: String,
    /// The user's comparison mode (wins over the model's suggestion).
    #[serde(default)]
    pub compare_mode: Option<CompareMode>,
}

impl GenerateRequest {
    /// Backend gate (the confirmation checkbox is the frontend gate).
    pub fn validate(&self) -> Result<&'static languages::LanguageConfig, AiError> {
        if self.task_text.trim().is_empty() {
            return Err(AiError::Other(
                "Die Aufgabenstellung ist leer – bitte zuerst den Aufgabentext einfügen.".into(),
            ));
        }
        let chars = self.task_text.chars().count();
        if chars > MAX_TASK_CHARS {
            return Err(AiError::Other(format!(
                "Die Aufgabenstellung ist zu lang für das KI-Modell ({chars} Zeichen, höchstens \
                 {MAX_TASK_CHARS}). Bitte auf die eigentliche Aufgabe kürzen."
            )));
        }
        if let Some(mode) = &self.compare_mode {
            mode.validate().map_err(AiError::Other)?;
        }
        languages::get(&self.language)
            .ok_or_else(|| AiError::Other(format!("Unbekannte Sprache: {}", self.language)))
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum TestSource {
    /// Example from the task sheet (input verbatim in the text).
    Sheet,
    /// Input generated by the model.
    Generated,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedTest {
    pub name: String,
    pub input: String,
    /// Output of the majority of verified solutions (executed, never
    /// written by the model).
    pub expected: String,
    pub source: TestSource,
    /// Share of surviving solutions that produced this output.
    pub agreement: f64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum ConfidenceLevel {
    Green,
    Yellow,
    Red,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Confidence {
    pub level: ConfidenceLevel,
    /// German reasons.
    pub reasons: Vec<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Stats {
    pub solutions_requested: usize,
    pub solutions_compiled: usize,
    pub solutions_repaired: usize,
    pub solutions_passed: usize,
    pub examples_found: usize,
    pub examples_discarded: usize,
    pub inputs_generated: usize,
    pub tests_dropped: usize,
    pub llm_calls: usize,
    pub completion_tokens: u64,
    pub tokens_per_second: Option<f64>,
    pub duration_ms: u64,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GenerateResult {
    pub tests: Vec<GeneratedTest>,
    /// The solution that agreed with the majority most often.
    pub reference_solution: Option<String>,
    pub confidence: Confidence,
    /// The model's suggestion; only applied when the user accepts it.
    pub suggested_compare_mode: Option<CompareMode>,
    /// The mode used for verification and majority vote.
    pub compare_mode: CompareMode,
    pub stats: Stats,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum Phase {
    Model,
    Structure,
    Solutions,
    Inputs,
    Majority,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct AiProgress {
    pub phase: Phase,
    /// German status line.
    pub message: String,
    pub current: Option<usize>,
    pub total: Option<usize>,
    pub tokens_per_second: Option<f64>,
}

impl AiProgress {
    pub fn new(phase: Phase, message: impl Into<String>) -> Self {
        Self {
            phase,
            message: message.into(),
            current: None,
            total: None,
            tokens_per_second: None,
        }
    }
}

/// Runs a program once per input in the sandbox. Errors (no engine, …)
/// abort the pipeline; compile failures are part of the result.
pub trait Executor {
    fn run(
        &self,
        language: &str,
        code: &str,
        inputs: &[String],
    ) -> impl Future<Output = Result<CollectedOutputs, AiError>> + Send;
}

/// [`Executor`] using the real sandbox.
pub struct SandboxExecutor {
    pub cancel: CancellationToken,
}

impl Executor for SandboxExecutor {
    async fn run(
        &self,
        language: &str,
        code: &str,
        inputs: &[String],
    ) -> Result<CollectedOutputs, AiError> {
        let run = crate::runner::collect_outputs(language, code, inputs, |_| {});
        tokio::select! {
            biased;
            _ = self.cancel.cancelled() => Err(AiError::Cancelled),
            r = run => r.map_err(|e| AiError::Other(e.to_string())),
        }
    }
}

